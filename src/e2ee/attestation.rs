// ── Quote binary layout (from sek8s utils/extract_tdx_quote.c) ──────────────

/// Quote header size in bytes.
pub const QUOTE_HEADER_SIZE: usize = 48;
/// TD report size in bytes.
pub const TD_REPORT_SIZE: usize = 584;
/// Minimum quote size: header + TD report.
pub const MIN_QUOTE_SIZE: usize = QUOTE_HEADER_SIZE + TD_REPORT_SIZE;

// Offsets within the TD report (relative to the TD report start, i.e. byte 48
// of the full quote).
const TD_REPORT_MRTD_OFFSET: usize = 136;
const TD_REPORT_RTMR0_OFFSET: usize = 328;
const TD_REPORT_RTMR1_OFFSET: usize = 376;
const TD_REPORT_RTMR2_OFFSET: usize = 424;
const TD_REPORT_RTMR3_OFFSET: usize = 472;
const TD_REPORT_REPORTDATA_OFFSET: usize = 520;

/// Size of each measurement register (MRTD, RTMR0-3) in bytes.
pub const REGISTER_SIZE: usize = 48;
/// Size of the REPORTDATA field in bytes.
pub const REPORTDATA_SIZE: usize = 64;

/// TDX TEE type in the quote header (`0x00000081`).
pub const TEE_TYPE_TDX: u32 = 0x0000_0081;
/// Expected quote version for TDX (ECDSA-256 with DCAP).
pub const QUOTE_VERSION_4: u16 = 4;

