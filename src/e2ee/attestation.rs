// ── TDX Quote parsing ───────────────────────────────────────────────────────

/// A parsed TDX quote: header fields + extracted TD report measurements.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct TdxQuote {
    /// Quote header version (expected 4 for TDX-DCAP).
    pub version: u16,
    /// Attestation key type (e.g. 2 for ECDSA-256).
    pub att_key_type: u16,
    /// TEE type (expected `0x00000081` for TDX).
    pub tee_type: u32,
    /// QE vendor ID (16 bytes).
    pub qe_vendor_id: [u8; 16],
    /// MRTD — 48 bytes.
    pub mrtd: [u8; REGISTER_SIZE],
    /// RTMR0 — 48 bytes.
    pub rtmr0: [u8; REGISTER_SIZE],
    /// RTMR1 — 48 bytes.
    pub rtmr1: [u8; REGISTER_SIZE],
    /// RTMR2 — 48 bytes.
    pub rtmr2: [u8; REGISTER_SIZE],
    /// RTMR3 — 48 bytes.
    pub rtmr3: [u8; REGISTER_SIZE],
    /// REPORTDATA — 64 bytes = nonce(32) || cert_hash(32).
    pub report_data: [u8; REPORTDATA_SIZE],
    /// The original raw quote bytes. Carried so `verify()` can pass them to
    /// `verify_dcap()` (which needs the full quote incl. auth data / signature,
    /// not just the parsed TD report fields).
    pub raw: Vec<u8>,
}

/// Errors that can arise during quote parsing or verification.
#[derive(Debug, PartialEq, Eq)]
pub enum AttestationError {
    /// Quote is too short (less than header + TD report).
    QuoteTooShort { len: usize },
    /// Quote version is not 4 (TDX-DCAP).
    InvalidVersion { got: u16 },
    /// TEE type is not `0x00000081` (TDX).
    InvalidTeeType { got: u32 },
    /// MRTD does not match the pinned expected value.
    MrtdMismatch {
        version: String,
        expected: String,
        got: String,
    },
    /// RTMR1 does not match.
    Rtmr1Mismatch {
        version: String,
        expected: String,
        got: String,
    },
    /// RTMR2 does not match.
    Rtmr2Mismatch {
        version: String,
        expected: String,
        got: String,
    },
    /// RTMR3 does not match.
    Rtmr3Mismatch {
        version: String,
        expected: String,
        got: String,
    },
    /// The guest image version has no pinned measurement — HARD FAIL.
    UnknownVersion { version: String },
    /// REPORTDATA nonce does not match the expected nonce.
    NonceMismatch { expected: String, got: String },
    /// REPORTDATA cert hash does not match the expected key hash.
    KeyBindingMismatch { expected: String, got: String },
    /// A hex measurement string is not valid hex or wrong length.
    InvalidHex { len: usize },
    /// The quote bytes are not valid base64.
    InvalidBase64,
}

impl std::fmt::Display for AttestationError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            AttestationError::QuoteTooShort { len } => {
                write!(f, "quote too short: {len} bytes (min {MIN_QUOTE_SIZE})")
            }
            AttestationError::InvalidVersion { got } => {
                write!(f, "invalid quote version: {got} (expected {QUOTE_VERSION_4})")
            }
            AttestationError::InvalidTeeType { got } => {
                write!(f, "invalid TEE type: 0x{got:08X} (expected 0x{TEE_TYPE_TDX:08X})")
            }
            AttestationError::MrtdMismatch { version, expected, got } => {
                write!(
                    f,
                    "MRTD mismatch for version {version}: expected {expected}, got {got}"
                )
            }
            AttestationError::Rtmr1Mismatch { version, expected, got } => {
                write!(
                    f,
                    "RTMR1 mismatch for version {version}: expected {expected}, got {got}"
                )
            }
            AttestationError::Rtmr2Mismatch { version, expected, got } => {
                write!(
                    f,
                    "RTMR2 mismatch for version {version}: expected {expected}, got {got}"
                )
            }
            AttestationError::Rtmr3Mismatch { version, expected, got } => {
                write!(
                    f,
                    "RTMR3 mismatch for version {version}: expected {expected}, got {got}"
                )
            }
            AttestationError::UnknownVersion { version } => {
                write!(f, "no pinned measurement for guest image version {version}")
            }
            AttestationError::NonceMismatch { expected, got } => {
                write!(f, "nonce mismatch: expected {expected}, got {got}")
            }
            AttestationError::KeyBindingMismatch { expected, got } => {
                write!(f, "key binding mismatch: expected {expected}, got {got}")
            }
            AttestationError::InvalidHex { len } => {
                write!(f, "invalid hex measurement string (len {len})")
            }
            AttestationError::InvalidBase64 => write!(f, "invalid base64 in quote"),
        }
    }
}

impl std::error::Error for AttestationError {}

/// Parse a raw TDX quote byte slice into a `TdxQuote`.
///
/// Validates the minimum size, quote version, and TEE type. Extracts MRTD,
/// RTMR0-3, and REPORTDATA from the TD report.
pub fn parse_quote(quote: &[u8]) -> Result<TdxQuote, AttestationError> {
    if quote.len() < MIN_QUOTE_SIZE {
        return Err(AttestationError::QuoteTooShort { len: quote.len() });
    }

    // Header fields (little-endian per Intel TDX quote format).
    let version = u16::from_le_bytes([quote[0], quote[1]]);
    let att_key_type = u16::from_le_bytes([quote[2], quote[3]]);
    let tee_type = u32::from_le_bytes([quote[4], quote[5], quote[6], quote[7]]);
    let mut qe_vendor_id = [0u8; 16];
    qe_vendor_id.copy_from_slice(&quote[16..32]);

    if version != QUOTE_VERSION_4 {
        return Err(AttestationError::InvalidVersion { got: version });
    }
    if tee_type != TEE_TYPE_TDX {
        return Err(AttestationError::InvalidTeeType { got: tee_type });
    }

    // TD report starts at offset 48.
    let td_report = &quote[QUOTE_HEADER_SIZE..];

    let extract = |offset: usize, size: usize| -> [u8; REGISTER_SIZE] {
        let mut buf = [0u8; REGISTER_SIZE];
        buf.copy_from_slice(&td_report[offset..offset + size]);
        buf
    };

    let mrtd = extract(TD_REPORT_MRTD_OFFSET, REGISTER_SIZE);
    let rtmr0 = extract(TD_REPORT_RTMR0_OFFSET, REGISTER_SIZE);
    let rtmr1 = extract(TD_REPORT_RTMR1_OFFSET, REGISTER_SIZE);
    let rtmr2 = extract(TD_REPORT_RTMR2_OFFSET, REGISTER_SIZE);
    let rtmr3 = extract(TD_REPORT_RTMR3_OFFSET, REGISTER_SIZE);

    let mut report_data = [0u8; REPORTDATA_SIZE];
    report_data.copy_from_slice(
        &td_report[TD_REPORT_REPORTDATA_OFFSET..TD_REPORT_REPORTDATA_OFFSET + REPORTDATA_SIZE],
    );

    Ok(TdxQuote {
        version,
        att_key_type,
        tee_type,
        qe_vendor_id,
        mrtd,
        rtmr0,
        rtmr1,
        rtmr2,
        rtmr3,
        report_data,
        raw: quote.to_vec(),
    })
}

/// Parse a base64-encoded TDX quote.
pub fn parse_quote_b64(quote_b64: &str) -> Result<TdxQuote, AttestationError> {
    let bytes = base64_decode(quote_b64).map_err(|_| AttestationError::InvalidBase64)?;
    parse_quote(&bytes)
}

// ── Hex helpers ─────────────────────────────────────────────────────────────

/// Convert a 48-byte register to a 96-char uppercase hex string.
pub fn reg_to_hex(reg: &[u8; REGISTER_SIZE]) -> String {
    let mut s = String::with_capacity(96);
    for b in reg {
        use std::fmt::Write;
        let _ = write!(s, "{b:02X}");
    }
    s
}

/// Convert a hex string to a 48-byte register. The string must be exactly
/// 96 hex chars (case-insensitive).
pub fn hex_to_reg(hex: &str) -> Result<[u8; REGISTER_SIZE], AttestationError> {
    if hex.len() != 96 {
        return Err(AttestationError::InvalidHex { len: hex.len() });
    }
    let mut reg = [0u8; REGISTER_SIZE];
    for (i, byte) in reg.iter_mut().enumerate() {
        *byte = u8::from_str_radix(&hex[i * 2..i * 2 + 2], 16)
            .map_err(|_| AttestationError::InvalidHex { len: hex.len() })?;
    }
    Ok(reg)
}

// ── Key binding ─────────────────────────────────────────────────────────────

/// Compute the SHA-256 hash of a public key (DER-encoded) and return it as
/// a 64-char lowercase hex string. This is the "cert_hash" half of REPORTDATA.
///
/// In the real Chutes attestation flow, the TEE hashes the DER encoding of
/// its proxy TLS certificate's public key. For the E2E client, the relevant
/// public key is the `e2e_pubkey` (ML-KEM-768 raw bytes). We hash those raw
/// bytes directly — the binding proves the quote was generated for THIS key.
pub fn pubkey_hash_hex(pubkey: &[u8]) -> String {
    let mut hasher = Sha256::new();
    hasher.update(pubkey);
    let digest = hasher.finalize();
    hex_lower(&digest)
}

/// Convert bytes to a lowercase hex string.
fn hex_lower(bytes: &[u8]) -> String {
    let mut s = String::with_capacity(bytes.len() * 2);
    for b in bytes {
        use std::fmt::Write;
        let _ = write!(s, "{b:02x}");
    }
    s
}

/// Extract the nonce (first 32 bytes) and cert_hash (last 32 bytes) from
/// REPORTDATA, both as lowercase hex strings.
pub fn split_report_data(report_data: &[u8; REPORTDATA_SIZE]) -> (String, String) {
    let nonce = hex_lower(&report_data[..32]);
    let cert_hash = hex_lower(&report_data[32..]);
    (nonce, cert_hash)
}

// ── Verification mode ────────────────────────────────────────────────────────

/// Whether attestation failures are hard (refuse to encrypt) or soft (warn).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum AttestationMode {
    /// Refuse to encrypt if attestation fails or is unavailable.
    Strict,
    /// Log a warning and proceed if attestation fails or is unavailable.
    Permissive,
}

impl Default for AttestationMode {
    fn default() -> Self {
        AttestationMode::Permissive
    }
}

/// Override for pinned measurements, allowing env-var or config-file updates.
#[derive(Clone, Debug, Default, serde::Deserialize, serde::Serialize, PartialEq, Eq)]
pub struct MeasurementOverride {
    pub mrtd: Option<String>,
    pub rtmr1: Option<String>,
    pub rtmr2: Option<String>,
    pub rtmr3: Option<String>,
}

impl MeasurementOverride {
    /// Build an override from environment variables:
    /// `CHUTES_TEE_MRTD`, `CHUTES_TEE_RTMR1`, `CHUTES_TEE_RTMR2`,
    /// `CHUTES_TEE_RTMR3`. Each is optional; unset vars yield `None`.
    ///
    /// This is the env-var update path (Step 3 of the attestation task):
    /// operators can pin a new guest image version's measurements without a
    /// code change by exporting these four variables.
    pub fn from_env() -> Self {
        Self::from_env_with(|k| std::env::var(k).ok())
    }

    /// Internal: build an override using a caller-supplied env getter. This
    /// lets tests exercise the env-var path without mutating the real process
    /// environment (which races under parallel test execution).
    pub(crate) fn from_env_with(mut get: impl FnMut(&str) -> Option<String>) -> Self {
        Self {
            mrtd: get("CHUTES_TEE_MRTD"),
            rtmr1: get("CHUTES_TEE_RTMR1"),
            rtmr2: get("CHUTES_TEE_RTMR2"),
            rtmr3: get("CHUTES_TEE_RTMR3"),
        }
    }

    /// Build an override from a JSON string (the config-file path).
    ///
    /// Accepted JSON: `{"mrtd": "...", "rtmr1": "...", "rtmr2": "...",
    /// "rtmr3": "..."}` with any subset of fields. Unknown fields are ignored.
    pub fn from_json(json: &str) -> Result<Self, serde_json::Error> {
        serde_json::from_str(json)
    }

    /// Read a config file from `path` and parse it as a JSON override.
    pub fn from_config_file(path: &str) -> Result<Self, std::io::Error> {
        let content = std::fs::read_to_string(path)?;
        Self::from_json(&content).map_err(|e| std::io::Error::new(std::io::ErrorKind::InvalidData, e))
    }

    /// True when no override field is set (i.e. the pinned table should be used).
    pub fn is_empty(&self) -> bool {
        self.mrtd.is_none()
            && self.rtmr1.is_none()
            && self.rtmr2.is_none()
            && self.rtmr3.is_none()
    }
}

/// The result of attestation verification.
#[derive(Clone, Debug)]
pub struct AttestationResult {
    /// Whether the quote passed all available checks.
    pub verified: bool,
    /// The guest image version that was matched (if any).
    pub version: Option<String>,
    /// Whether the DCAP cryptographic signature was verified (requires Intel
    /// PCS collateral — supplied via `VerifyParams.collateral`). `false` when
    /// no collateral was provided (the fallback, measurement-only path).
    pub signature_verified: bool,
    /// Whether the MRTD/RTMR measurements matched the pinned table.
    pub measurements_verified: bool,
    /// Whether the REPORTDATA nonce + key binding matched.
    pub key_binding_verified: bool,
    /// The Intel TCB status from DCAP verification (e.g. "UpToDate",
    /// "OutOfDate"). `None` when no collateral was supplied.
    pub tcb_status: Option<String>,
    /// Human-readable summary of what was checked.
    pub summary: String,
}

// ── Verification ───────────────────────────────────────────────────────────

/// Parameters for attestation verification.
#[derive(Clone, Debug)]
pub struct VerifyParams<'a> {
    /// The guest image version to check against (e.g. "1.5.0").
    pub expected_version: &'a str,
    /// The expected nonce (64 hex chars = 32 bytes) that the quote should bind.
    pub expected_nonce: &'a str,
    /// The TEE's public key (raw bytes) to verify key binding against.
    pub expected_pubkey: &'a [u8],
    /// Pinned-measurement override (env-var/config-file path).
    pub override_measurements: Option<&'a MeasurementOverride>,
    /// Strict or permissive mode.
    pub mode: AttestationMode,
    /// Optional Intel PCS collateral. When present, `verify()` also performs
    /// the DCAP cryptographic signature verification (the Intel-attended root
    /// of the chain) and sets `signature_verified` / `tcb_status` accordingly.
    pub collateral: Option<&'a DcapCollateral>,
    /// Verification time (unix seconds) for the DCAP check. Must fall inside the
    /// collateral's validity window. Ignored when `collateral` is `None`.
    pub now_secs: u64,
}

impl<'a> Default for VerifyParams<'a> {
    fn default() -> Self {
        Self {
            expected_version: "",
            expected_nonce: "",
            expected_pubkey: &[],
            override_measurements: None,
            mode: AttestationMode::default(),
            collateral: None,
            now_secs: 0,
        }
    }
}

/// Verify a parsed TDX quote against pinned measurements and key binding.
///
/// Returns an `AttestationResult`. In strict mode, a non-verified result
/// should cause the caller to refuse encryption; in permissive mode the
/// caller logs and proceeds.
///
/// This function checks:
/// 1. MRTD, RTMR1, RTMR2, RTMR3 match the pinned values for the version
///    (or the override if provided).
/// 2. REPORTDATA nonce matches `expected_nonce`.
/// 3. REPORTDATA cert_hash matches SHA-256 of `expected_pubkey`.
///
/// It does NOT verify the quote's cryptographic signature (DCAP) — that
/// requires Intel PCS collateral and is the trusted-root step documented
/// separately. `signature_verified` in the result is always `false` here.
pub fn verify(quote: &TdxQuote, params: &VerifyParams<'_>) -> AttestationResult {
    // Resolve the expected measurements: override > pinned table.
    let (exp_mrtd, exp_rtmr1, exp_rtmr2, exp_rtmr3) = match params.override_measurements {
        Some(o) => (
            o.mrtd.as_deref().unwrap_or(""),
            o.rtmr1.as_deref().unwrap_or(""),
            o.rtmr2.as_deref().unwrap_or(""),
            o.rtmr3.as_deref().unwrap_or(""),
        ),
        None => match pinned_measurement_for_version(params.expected_version) {
            Some(m) => (m.mrtd, m.rtmr1, m.rtmr2, m.rtmr3),
            None => {
                return AttestationResult {
                    verified: false,
                    version: None,
                    signature_verified: false,
                    measurements_verified: false,
                    key_binding_verified: false,
                    tcb_status: None,
                    summary: format!(
                        "no pinned measurement for version {} — attestation cannot be verified",
                        params.expected_version
                    ),
                };
            }
        },
    };

    // Compare measurements (case-insensitive hex).
    let got_mrtd = reg_to_hex(&quote.mrtd);
    let got_rtmr1 = reg_to_hex(&quote.rtmr1);
    let got_rtmr2 = reg_to_hex(&quote.rtmr2);
    let got_rtmr3 = reg_to_hex(&quote.rtmr3);

    let mrtd_ok = got_mrtd.eq_ignore_ascii_case(exp_mrtd) && !exp_mrtd.is_empty();
    let rtmr1_ok = got_rtmr1.eq_ignore_ascii_case(exp_rtmr1) && !exp_rtmr1.is_empty();
    let rtmr2_ok = got_rtmr2.eq_ignore_ascii_case(exp_rtmr2) && !exp_rtmr2.is_empty();
    let rtmr3_ok = got_rtmr3.eq_ignore_ascii_case(exp_rtmr3) && !exp_rtmr3.is_empty();
    let measurements_verified = mrtd_ok && rtmr1_ok && rtmr2_ok && rtmr3_ok;

    // Key binding: REPORTDATA = nonce(32) || cert_hash(32).
    let (got_nonce, got_cert_hash) = split_report_data(&quote.report_data);
    let exp_cert_hash = pubkey_hash_hex(params.expected_pubkey);
    let nonce_ok = got_nonce.eq_ignore_ascii_case(params.expected_nonce)
        && !params.expected_nonce.is_empty();
    let key_ok = got_cert_hash.eq_ignore_ascii_case(&exp_cert_hash);
    let key_binding_verified = nonce_ok && key_ok;

    // DCAP cryptographic signature verification (Intel-attended root of chain).
    // Only performed when collateral is supplied; otherwise signature_verified
    // stays false and we rely on measurement + key binding alone.
    let (signature_verified, tcb_status) = match params.collateral {
        Some(coll) => {
            // Re-serialize the parsed quote to raw bytes for DCAP. We parse from
            // raw bytes in verify_dcap, but we only have a TdxQuote here. To
            // avoid a redundant re-parse, verify_dcap takes raw bytes — so we
            // need the original raw quote. Since verify() receives a parsed
            // quote, we reconstruct by re-parsing is not possible; instead we
            // store the raw bytes on TdxQuote for this purpose.
            // (See TdxQuote::raw — we carry the original bytes.)
            let dcap = verify_dcap(&quote.raw, coll, params.now_secs);
            (dcap.signature_verified, dcap.tcb_status)
        }
        None => (false, None),
    };

    // `verified` requires measurements + key binding AND (when collateral was
    // supplied) a passing DCAP signature. When no collateral is supplied we
    // fall back to measurement + key binding alone (signature_verified=false).
    let verified = measurements_verified
        && key_binding_verified
        && (params.collateral.is_none() || signature_verified);
    let mode_str = match params.mode {
        AttestationMode::Strict => "strict",
        AttestationMode::Permissive => "permissive",
    };
    let summary = if verified {
        format!(
            "attestation verified ({mode_str}): version {} measurements + key binding match",
            params.expected_version
        )
    } else {
        let mut fails = Vec::new();
        if !mrtd_ok {
            fails.push("MRTD");
        }
        if !rtmr1_ok {
            fails.push("RTMR1");
        }
        if !rtmr2_ok {
            fails.push("RTMR2");
        }
        if !rtmr3_ok {
            fails.push("RTMR3");
        }
        if !nonce_ok {
            fails.push("nonce");
        }
        if !key_ok {
            fails.push("key-binding");
        }
        if params.collateral.is_some() && !signature_verified {
            fails.push("DCAP-signature");
        }
        format!(
            "attestation failed ({mode_str}): {} mismatch for version {}",
            fails.join(", "),
            params.expected_version
        )
    };

    AttestationResult {
        verified,
        version: Some(params.expected_version.to_string()),
        signature_verified,
        measurements_verified,
        key_binding_verified,
        tcb_status,
        summary,
    }
}

/// Decide whether to proceed with encryption based on the attestation result
/// and the mode.
///
/// - Strict: proceed only if `verified` is true.
/// - Permissive: always proceed (log the summary).
///
/// Returns `Ok(())` to proceed, or `Err(AttestationError)` in strict mode.
pub fn should_proceed(result: &AttestationResult, mode: AttestationMode) -> Result<(), AttestationError> {
    match mode {
        AttestationMode::Strict if !result.verified => Err(attestation_failure_error(result)),
        _ => {
            log::info!("attestation: {}", result.summary);
            Ok(())
        }
    }
}

/// Construct an `AttestationError` describing the attestation failure.
fn attestation_failure_error(result: &AttestationResult) -> AttestationError {
    // Reuse a generic representation; the summary carries the detail.
    AttestationError::UnknownVersion {
        version: result.summary.clone(),
    }
}

// ── Helpers for building mock quotes (tests + integration) ──────────────────

/// Build a synthetic TDX quote with the given measurements and report data.
///
/// Used by tests and integration mocks. NOT for production use — a real quote
/// is hardware-signed and cannot be constructed offline.
#[cfg(test)]
pub(crate) fn build_mock_quote(
    mrtd: &[u8; REGISTER_SIZE],
    rtmr0: &[u8; REGISTER_SIZE],
    rtmr1: &[u8; REGISTER_SIZE],
    rtmr2: &[u8; REGISTER_SIZE],
    rtmr3: &[u8; REGISTER_SIZE],
    report_data: &[u8; REPORTDATA_SIZE],
) -> Vec<u8> {
    let mut quote = vec![0u8; MIN_QUOTE_SIZE];
    // Header: version=4, att_key_type=2, tee_type=0x81
    quote[0..2].copy_from_slice(&QUOTE_VERSION_4.to_le_bytes());
    quote[2..4].copy_from_slice(&2u16.to_le_bytes());
    quote[4..8].copy_from_slice(&TEE_TYPE_TDX.to_le_bytes());
    // qe_vendor_id and user_data stay zero.

    // TD report at offset 48.
    let td = &mut quote[QUOTE_HEADER_SIZE..];
    td[TD_REPORT_MRTD_OFFSET..TD_REPORT_MRTD_OFFSET + REGISTER_SIZE].copy_from_slice(mrtd);
    td[TD_REPORT_RTMR0_OFFSET..TD_REPORT_RTMR0_OFFSET + REGISTER_SIZE].copy_from_slice(rtmr0);
    td[TD_REPORT_RTMR1_OFFSET..TD_REPORT_RTMR1_OFFSET + REGISTER_SIZE].copy_from_slice(rtmr1);
    td[TD_REPORT_RTMR2_OFFSET..TD_REPORT_RTMR2_OFFSET + REGISTER_SIZE].copy_from_slice(rtmr2);
    td[TD_REPORT_RTMR3_OFFSET..TD_REPORT_RTMR3_OFFSET + REGISTER_SIZE].copy_from_slice(rtmr3);
    td[TD_REPORT_REPORTDATA_OFFSET..TD_REPORT_REPORTDATA_OFFSET + REPORTDATA_SIZE]
        .copy_from_slice(report_data);
    quote
}

/// Build REPORTDATA from a nonce hex string and a public key.
#[cfg(test)]
pub(crate) fn build_report_data(nonce_hex: &str, pubkey: &[u8]) -> [u8; REPORTDATA_SIZE] {
    let mut rd = [0u8; REPORTDATA_SIZE];
    // Nonce: 32 bytes from 64 hex chars.
    for (i, byte) in rd[..32].iter_mut().enumerate() {
        *byte = u8::from_str_radix(&nonce_hex[i * 2..i * 2 + 2], 16).unwrap_or(0);
    }
    // Cert hash: SHA-256 of pubkey.
    let mut hasher = Sha256::new();
    hasher.update(pubkey);
    let digest = hasher.finalize();
    rd[32..].copy_from_slice(&digest);
    rd
}

// ── DCAP cryptographic signature verification (Intel-attended chain) ──────────
//
// `dcap-qvl` is a pure-Rust implementation of Intel's DCAP Quote Verification
// Library. It verifies the quote's signature chain back to Intel's hardware
// root key (embedded `TrustedRootCA.der`), checks the TCB info is current and
// not revoked, and extracts the verified report. This is the trusted root of
// the attestation chain: a measurement/nonce match alone cannot prove the
// quote came from genuine Intel TDX hardware — only the DCAP signature chain
// can.
//
// Full verification requires Intel PCS collateral (PCK cert chain, TCB info,
// QE identity, CRLs). When collateral is supplied, `verify_dcap` performs the
// genuine hardware verification. When it is not (the live Chutes API does not
// hand out collateral), the caller falls back to measurement+nonce checks
// alone and `signature_verified` stays `false`.

/// Intel PCS collateral for a TDX quote, matching `dcap_qvl::QuoteCollateralV3`.
///
/// Re-exported as a type alias so callers do not need to depend on `dcap-qvl`
/// directly. Serialize/deserialize is identical to the JSON the Intel PCS
/// (or a PCCS) returns.
pub type DcapCollateral = dcap_qvl::QuoteCollateralV3;

/// Result of DCAP cryptographic verification.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct DcapResult {
    /// True iff the quote's signature chain verified against Intel's root CA
    /// AND the TCB status is acceptable (not revoked / out of date).
    pub signature_verified: bool,
    /// The TCB status string from Intel's QVL (e.g. "UpToDate", "OutOfDate").
    pub tcb_status: Option<String>,
    /// Advisory IDs for the matched TCB level (empty when none).
    pub advisory_ids: Vec<String>,
    /// Human-readable summary.
    pub summary: String,
}

/// Verify a raw TDX quote's cryptographic signature against Intel's PCS
/// collateral using the pure-Rust `dcap-qvl` verifier with the embedded Intel
/// root CA.
///
/// `now_secs` is the verification time (unix seconds); it must fall inside the
/// collateral's validity window (`issueDate`..`nextUpdate`) for the TCB info
/// and CRLs. Outside that window verification fails with a freshness error.
///
/// This is the Intel-attended step: it proves the quote was signed by genuine
/// Intel TDX hardware, not an emulator or a forged quote. It does NOT compare
/// MRTD/RTMR against pinned measurements — that is `verify()`'s job. Together,
/// `verify_dcap` + `verify` form the full chain: hardware authenticity +
/// image identity + key binding.
pub fn verify_dcap(
    raw_quote: &[u8],
    collateral: &DcapCollateral,
    now_secs: u64,
) -> DcapResult {
    match dcap_qvl::verify::verify(raw_quote, collateral, now_secs) {
        Ok(report) => {
            let status = report.status.clone();
            let adv = report.advisory_ids.clone();
            // "UpToDate" and "SWHardeningNeeded" are acceptable; anything else
            // (OutOfDate, ConfigurationNeeded, revoked) fails verification.
            let verified = matches!(
                status.as_str(),
                "UpToDate" | "SWHardeningNeeded"
            );
            DcapResult {
                signature_verified: verified,
                tcb_status: Some(status.clone()),
                advisory_ids: adv,
                summary: format!("DCAP verify: status={status}"),
            }
        }
        Err(e) => DcapResult {
            signature_verified: false,
            tcb_status: None,
            advisory_ids: Vec::new(),
            summary: format!("DCAP verify failed: {e:#}"),
        },
    }
}

