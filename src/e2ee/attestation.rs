//! TDX attestation verification for the E2E module.
//!
//! This module implements client-side verification of Intel TDX attestation
//! quotes, following the Intel DCAP quote verification model:
//!
//! 1. **Quote parsing** — parse a raw TDX quote (header + TD report) to extract
//!    MRTD, RTMR0-3, and REPORTDATA.
//! 2. **Measurement pinning** — compare the quote's MRTD/RTMR1-3 against a
//!    hard-coded table of known-good values per guest image version. The
//!    pinned values are sourced from `api.chutes.ai/servers/tdx/measurements`
//!    (the Chutes published measurement registry, itself reproducible from
//!    the sek8s release tags).
//! 3. **Key binding** — verify that the quote's REPORTDATA binds the TEE's
//!    public key (via a cert hash) and a nonce, so the quote cannot be
//!    replayed against a different key.
//! 4. **Strict vs permissive mode** — in strict mode, attestation failure
//!    refuses encryption; in permissive mode it logs a warning and proceeds.
//!
//! ## What is and is not verifiable by this client
//!
//! The Chutes `api.chutes.ai/e2e/instances/{chute_id}` endpoint returns ONLY
//! `{instance_id, e2e_pubkey, nonces}` — no TDX quote, no measurement material.
//! The real TDX quote is generated by a per-VM attestation-proxy (sek8s
//! `src/attestation-proxy`, port 8443, `/server/attest?nonce=...`) reachable
//! only inside the Chutes cluster network — the E2E client cannot fetch it
//! directly. There is no public `/e2e/quote/{id}` or `/e2e/attestation/{id}`
//! endpoint (all return 404).
//!
//! **However**, the user-reachable evidence endpoint
//! `GET /instances/{id}/evidence?nonce=<64-hex>` proxies the miner's
//! attestation service and returns a real TDX quote + cert + GPU evidence.
//! When `AttestationConfig::node_ip` is `None`, `e2e_request_attested` can
//! still fetch a live quote via this evidence path (see `handler.rs`), then
//! verify it with DCAP against Intel PCS when `collateral_url` is set. The
//! raw `:30443/server/attest` hop below remains validator-gated and is the
//! only path that is truly unreachable by a user API client.
//!
//! Consequently this module provides:
//! - A `TdxQuote` parser that works on any raw quote bytes (for when a quote
//!   is supplied by a caller, a future API field, or a test fixture).
//! - A `MeasurementTable` of pinned known-good MRTD/RTMR values per guest
//!   image version, copied from `api.chutes.ai/servers/tdx/measurements`.
//! - A `verify()` function that checks (a) quote structure, (b) MRTD/RTMR
//!   match against the pinned table, (c) the REPORTDATA nonce/key binding.
//!
//! The Intel DCAP cryptographic signature verification (proving the quote
//! was signed by genuine Intel hardware via Intel PCS collateral) is the
//! trusted root of the chain and is performed by `dcap-qvl` when a quote and
//! its collateral are available. Without network access to Intel PCS, the
//! signature check is skipped — and that limitation is documented in
//! `AttestationResult` so callers can see exactly what was and was not
//! verified.

