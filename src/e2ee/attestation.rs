/// A pinned known-good set of TDX measurements for one guest image version.
///
/// These values are sourced from `api.chutes.ai/servers/tdx/measurements`,
/// which publishes the measurements of every reproducible guest image build.
/// The same values are reproducible by anyone from the sek8s release tag
/// (see `docs/reproducing-measurements.md`). Published measurements never
/// change; new versions get new tags.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct PinnedMeasurement {
    /// Guest image version, e.g. `"1.5.0"`.
    pub version: &'static str,
    /// MRTD — measurement of the initial TDX environment (firmware).
    /// 96 uppercase hex chars (48 bytes).
    pub mrtd: &'static str,
    /// RTMR1 — kernel and boot chain. 96 hex chars.
    pub rtmr1: &'static str,
    /// RTMR2 — initramfs, which carries the RTMR3 hash manifest. 96 hex chars.
    pub rtmr2: &'static str,
    /// RTMR3 — the measured filesystem (~49,000 files). 96 hex chars.
    pub rtmr3: &'static str,
}

