    // ── DCAP cryptographic signature verification (Intel-attended chain) ──────
    //
    // These tests use a REAL hardware-signed TDX quote + Intel PCS collateral
    // vendored from the dcap-qvl crate's sample/ directory. They exercise the
    // genuine Intel DCAP verification path (QuoteVerifier + embedded Intel root
    // CA), proving the quote was signed by genuine Intel hardware — the trusted
    // root of the chain that the local measurement/nonce checks alone cannot
